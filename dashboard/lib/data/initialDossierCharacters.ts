import { DossierCharacterEntry, CharacterLinkValue } from "@/lib/store/dashboardStore";

/**
 * Resolves editable link metadata safely for any character link field.
 */
export function resolveLinkDetails(
  linkVal: CharacterLinkValue | undefined,
  defaultUrlFallback: string
) {
  if (!linkVal) {
    return {
      activeUrl: defaultUrlFallback,
      defaultUrl: defaultUrlFallback,
      customUrl: undefined,
      isDisabled: false,
    };
  }

  if (typeof linkVal === "string") {
    return {
      activeUrl: linkVal || defaultUrlFallback,
      defaultUrl: defaultUrlFallback,
      customUrl: linkVal !== defaultUrlFallback ? linkVal : undefined,
      isDisabled: false,
    };
  }

  const defaultUrl = linkVal.defaultUrl || defaultUrlFallback;
  const activeUrl = linkVal.customUrl || defaultUrl;
  const isDisabled = !!linkVal.isDisabled;

  return {
    activeUrl,
    defaultUrl,
    customUrl: linkVal.customUrl,
    isDisabled,
  };
}

